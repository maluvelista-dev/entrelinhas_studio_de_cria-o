import { test, expect } from '@playwright/test';
import sharp from 'sharp';
test('edita pivô e anchor visualmente, persiste hierarquia e perspectivas independentes', async ({ page }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByLabel('Usuário', { exact: true }).fill(process.env.E2E_USERNAME);
  await page.getByLabel('Senha', { exact: true }).fill(process.env.E2E_PASSWORD);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await page.getByRole('button', { name: /Biblioteca/ }).click();
  const name = 'Personagem articulado ' + Date.now();
  const buffer = await sharp({ create: { width: 256, height: 256, channels: 4, background: '#8866cc80' } }).png().toBuffer();
  await page.getByLabel('Nome do elemento').fill(name);
  await page.getByRole('button', { name: 'Cadastrar elemento' }).click();
  const beforeCount = (await (await page.request.get('/api/internal/library')).json()).length;
  await page.getByRole('button', { name: 'Abrir ' + name, exact: true }).click();
  await page.getByRole('button', { name: 'Perspectivas e partes' }).click();
  await expect(page.getByRole('heading', { name: 'Estrutura de ' + name })).toBeVisible();
  await page.getByRole('button', { name: 'Adicionar parte', exact: true }).click();
  await page.getByLabel('Enviar imagem desta parte').setInputFiles({ name: 'body-front.png', mimeType: 'image/png', buffer });
  await page.getByRole('button', { name: 'Enviar e vincular imagem' }).click();
  await expect(page.getByText('Imagem enviada e vinculada à parte. Estrutura salva.', { exact: true })).toBeVisible();
  expect((await (await page.request.get('/api/internal/library')).json()).length).toBe(beforeCount);
  const frontAsset = await page.getByLabel('Imagem da parte').inputValue();
  const stage = page.getByRole('img', { name: 'Editor visual do personagem' });
  await expect(page.getByRole('img', { name: 'Montagem do personagem no Engine' })).toBeVisible();
  await expect(stage.locator('[data-part="body"]')).toHaveCount(1);
  const artwork = page.getByRole('img', { name: 'Montagem do personagem no Engine' });
  await expect.poll(() => artwork.evaluate(canvas => {
    const gl = canvas.getContext('webgl2') || canvas.getContext('webgl'); const pixel = new Uint8Array(4);
    gl.readPixels(Math.floor(canvas.width * 448 / 1152), canvas.height - 1 - Math.floor(canvas.height * 448 / 1152), 1, 1, gl.RGBA, gl.UNSIGNED_BYTE, pixel);
    return pixel[2] > pixel[0] && pixel[0] > pixel[1];
  })).toBe(true);
  async function client(x, y) {
    return stage.evaluate((svg, coordinates) => { const point = new DOMPoint(coordinates.x, coordinates.y).matrixTransform(svg.getScreenCTM()); return { x: point.x, y: point.y }; }, { x, y });
  }
  await page.getByLabel('Ferramenta visual').selectOption('pivot');
  await stage.scrollIntoViewIfNeeded();
  let point = await client(320, 384); await page.mouse.click(point.x, point.y);
  await expect(page.getByLabel('Pivô X', { exact: true })).toHaveValue('0.25');
  await expect(page.getByLabel('Pivô Y', { exact: true })).toHaveValue('0.5');
  await page.getByRole('button', { name: 'Adicionar anchor', exact: true }).click();
  await stage.scrollIntoViewIfNeeded();
  point = await client(384, 384); await page.mouse.move(point.x, point.y); await page.mouse.down();
  point = await client(448, 448); await page.mouse.move(point.x, point.y, { steps: 4 }); await page.mouse.up();
  await expect(page.getByLabel('Anchor X', { exact: true })).toHaveValue('0.75');
  await expect(page.getByLabel('Anchor Y', { exact: true })).toHaveValue('0.75');
  await page.getByLabel('Rotação (graus)').fill('90');
  await expect.poll(async () => Number(await stage.locator('[data-anchor="hand"]').getAttribute('cx'))).toBeCloseTo(256, 2);
  await expect.poll(async () => Number(await stage.locator('[data-anchor="hand"]').getAttribute('cy'))).toBeCloseTo(512, 2);
  await page.getByLabel('Identificador da nova parte').fill('hand');
  await page.getByRole('button', { name: 'Adicionar parte', exact: true }).click();
  await expect(page.getByLabel('Parte-pai')).toHaveValue('body');
  await expect(page.getByLabel('Parte-pai').locator('option[value="hand"]')).toHaveCount(0);
  await page.getByRole('button', { name: 'Duplicar perspectiva', exact: true }).click();
  await expect(page.getByLabel('Perspectiva do personagem')).toHaveValue('side');
  await page.getByRole('button', { name: 'body Filha de root', exact: true }).click();
  await page.getByLabel('Rotação (graus)').fill('0');
  await page.getByLabel('Enviar imagem desta parte').setInputFiles({ name: 'body-side.png', mimeType: 'image/png', buffer });
  await page.getByRole('button', { name: 'Enviar e vincular imagem' }).click();
  await expect(page.getByLabel('Imagem da parte')).not.toHaveValue(frontAsset);
  const sideAsset = await page.getByLabel('Imagem da parte').inputValue();
  expect((await (await page.request.get('/api/internal/library')).json()).length).toBe(beforeCount);
  await page.getByRole('button', { name: 'Salvar estrutura', exact: true }).click();
  await expect(page.getByText('Estrutura salva.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'body Filha de root', exact: true }).click();
  await expect(page.getByLabel('Rotação (graus)')).toHaveValue('90');
  await page.screenshot({ path: '.local/qa-rig-editor.png', fullPage: true });
  await page.reload(); await page.getByRole('button', { name: /Biblioteca/ }).click();
  await page.getByRole('button', { name: 'Abrir ' + name, exact: true }).click();
  await page.getByRole('button', { name: 'Perspectivas e partes' }).click();
  await page.getByRole('button', { name: 'body Filha de root', exact: true }).click();
  await expect(page.getByLabel('Pivô X', { exact: true })).toHaveValue('0.25');
  await expect(page.getByLabel('Imagem da parte')).toHaveValue(frontAsset);
  await page.getByLabel('Anchor selecionado').selectOption('hand');
  await expect(page.getByLabel('Anchor X', { exact: true })).toHaveValue('0.75');
  await page.getByLabel('Perspectiva do personagem').selectOption('side');
  await page.getByRole('button', { name: 'body Filha de root', exact: true }).click();
  await expect(page.getByLabel('Rotação (graus)')).toHaveValue('0');
  await expect(page.getByLabel('Imagem da parte')).toHaveValue(sideAsset);
  await page.getByLabel('Posição X').fill('500');
  page.once('dialog', dialog => dialog.dismiss());
  await page.getByRole('button', { name: 'Voltar à ficha', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Estrutura de ' + name })).toBeVisible();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Recarregar estrutura' }).click();
  await expect(page.getByLabel('Perspectiva do personagem')).toHaveValue('front');
  expect(errors).toEqual([]);
});
