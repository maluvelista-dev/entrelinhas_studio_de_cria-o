import { test, expect } from '@playwright/test';
test('criar, editar, ordenar, revisar e recarregar um livro', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  const stamp = Date.now();
  const title = 'A floresta dos sonhos ' + stamp;
  await page.goto('/');
  await page.getByLabel('Usuário', { exact: true }).fill(process.env.E2E_USERNAME);
  await page.getByLabel('Senha', { exact: true }).fill(process.env.E2E_PASSWORD);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await page.getByRole('button', { name: /Novo livro/ }).click();
  await page.getByLabel('Título do livro').fill(title);
  await page.getByLabel('Título do livro').press('Tab');
  await expect(page.getByLabel('Identificador (slug)')).toBeFocused();
  await page.getByLabel('Identificador (slug)').fill('floresta-' + stamp);
  await page.getByLabel('Descrição').fill('Uma história sobre amizade e descobertas.');
  await page.getByLabel('Idade mínima').fill('3');
  await page.getByLabel('Idade máxima').fill('7');
  await page.getByRole('button', { name: 'Criar livro', exact: true }).click();
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
  await page.getByRole('tab', { name: 'Páginas', exact: true }).click();
  await page.getByRole('button', { name: 'Adicionar página' }).click();
  await page.getByLabel('Texto da página').fill('Era uma vez uma raposa chamada Luna. 🦊');
  await page.getByRole('button', { name: 'Salvar página' }).click();
  await expect(page.getByText('Alterações não salvas')).toHaveCount(0);
  await page.getByRole('button', { name: 'Adicionar página' }).click();
  await page.getByRole('button', { name: /02 Página em branco/ }).click();
  await page.getByLabel('Texto da página').fill('Ela encontrou uma árvore que contava histórias.');
  await page.getByRole('button', { name: 'Salvar página' }).click();
  await page.getByRole('button', { name: 'Mover página 2 para cima' }).click();
  await expect(page.getByRole('heading', { name: 'Página 1', exact: true })).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: '.local/qa-editor.png', fullPage: true });
  await page.getByRole('tab', { name: 'Revisão', exact: true }).click();
  await page.getByLabel('Comentário opcional').fill('Texto pronto para leitura editorial.');
  await page.getByRole('button', { name: 'Enviar para revisão' }).click();
  await expect(page.getByText('Rascunho → Em revisão', { exact: true })).toBeVisible();
  await page.getByRole('tab', { name: 'Sobre o livro' }).click();
  await expect(page.getByLabel('Título do livro')).toBeDisabled();
  await page.getByRole('tab', { name: 'Revisão', exact: true }).click();
  await page.getByRole('button', { name: 'Devolver a rascunho' }).click();
  await expect(page.getByText('Em revisão → Rascunho', { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: new RegExp(title) }).click();
  await expect(page.getByLabel('Descrição')).toHaveValue('Uma história sobre amizade e descobertas.');
  await page.getByRole('tab', { name: 'Páginas', exact: true }).click();
  await expect(page.getByLabel('Texto da página')).toHaveValue('Ela encontrou uma árvore que contava histórias.');
  await page.getByRole('button', { name: /Biblioteca/ }).click();
  await page.getByLabel('Nome do elemento').fill('Luna ' + stamp);
  await page.getByRole('button', { name: 'Cadastrar elemento' }).click();
  await expect(page.getByText('Luna ' + stamp, { exact: true })).toBeVisible();
  await page.screenshot({ path: '.local/qa-library.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: '.local/qa-mobile-width.png', fullPage: true });
  expect(errors).toEqual([]);
});

test('administrador gerencia acessos e revisor permanece em consulta', async ({ page }) => {
  const username = 'review-' + Date.now();
  const password = 'Browser-test-password-2026!';
  await page.goto('/');
  await page.getByLabel('Usuário', { exact: true }).fill(process.env.E2E_USERNAME);
  await page.getByLabel('Senha', { exact: true }).fill(process.env.E2E_PASSWORD);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await page.getByRole('button', { name: /Acessos/ }).click();
  await page.getByLabel('Nome de exibição').fill('Revisão editorial');
  await page.getByLabel('Usuário de acesso').fill(username);
  await page.getByRole('combobox', { name: 'Perfil', exact: true }).selectOption('REVIEWER');
  await page.getByLabel('Senha inicial').fill(password);
  await page.getByRole('button', { name: 'Criar acesso', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Editar acesso de ' + username })).toBeVisible();
  await page.screenshot({ path: '.local/qa-access.png', fullPage: true });
  await page.getByRole('button', { name: 'Sair', exact: true }).click();
  await page.getByLabel('Usuário', { exact: true }).fill(username);
  await page.getByLabel('Senha', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Sua estante' })).toBeVisible();
  await expect(page.getByRole('button', { name: /Novo livro/ })).toHaveCount(0);
  await expect(page.getByRole('button', { name: /Acessos/ })).toHaveCount(0);
  await page.getByRole('button', { name: /Biblioteca/ }).click();
  await expect(page.getByRole('button', { name: 'Cadastrar elemento' })).toBeDisabled();
  await page.getByRole('button', { name: /^Abrir / }).first().click();
  await expect(page.getByLabel('Nome do elemento')).toBeDisabled();
  await expect(page.getByLabel('Descrição do elemento')).toBeDisabled();
  await expect(page.getByLabel('Imagem do elemento')).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Salvar cadastro' })).toHaveCount(0);
  expect(await page.evaluate(() => localStorage.length)).toBe(0);
  expect(await page.evaluate(() => document.cookie)).not.toContain('studio_session');
  await page.getByRole('button', { name: 'Sair', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Entrar', exact: true })).toBeVisible();
});
