import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import sharp from 'sharp';

test('exporta e importa personagem completo, cria poses e animações e persiste a cena', async ({ page }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const stamp = Date.now(), name = 'Luna animada ' + stamp, title = 'Livro animado ' + stamp;
  await page.goto('/');
  await page.getByLabel('Usuário', { exact: true }).fill(process.env.E2E_USERNAME);
  await page.getByLabel('Senha', { exact: true }).fill(process.env.E2E_PASSWORD);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await page.getByRole('button', { name: /Biblioteca/ }).click();
  await page.getByLabel('Nome do elemento').fill(name);
  await page.getByRole('button', { name: 'Cadastrar elemento' }).click();
  await page.getByRole('button', { name: 'Abrir ' + name, exact: true }).click();
  await page.getByRole('button', { name: 'Perspectivas e partes' }).click();
  await page.getByRole('button', { name: 'Adicionar parte', exact: true }).click();
  const buffer = await sharp({ create: { width: 256, height: 128, channels: 4, background: '#8855cc' } }).png().toBuffer();
  await page.getByLabel('Enviar imagem desta parte').setInputFiles({ name: 'body.png', mimeType: 'image/png', buffer });
  await page.getByRole('button', { name: 'Enviar e vincular imagem' }).click();
  await expect(page.getByText('Imagem enviada e vinculada à parte. Estrutura salva.', { exact: true })).toBeVisible();
  await page.getByLabel('Nome da pose', { exact: true }).fill('Em pé ' + stamp);
  await page.getByRole('button', { name: 'Salvar pose atual', exact: true }).click();
  await expect(page.getByText('Pose salva na Biblioteca.', { exact: true })).toBeVisible();
  await page.getByLabel('Nome da animação', { exact: true }).fill('Balanço ' + stamp);
  await page.getByRole('button', { name: 'Capturar keyframe', exact: true }).click();
  await page.getByLabel('Rotação (graus)', { exact: true }).fill('90');
  await page.getByRole('button', { name: 'Capturar keyframe', exact: true }).click();
  await page.getByRole('button', { name: 'Salvar animação', exact: true }).click();
  await expect(page.getByText('Animação salva na Biblioteca.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Testar keyframes', exact: true }).click();
  await expect(page.getByText('Prévia pronta.', { exact: true })).toBeVisible();
  const canvas = page.getByRole('img', { name: 'Prévia da cena animada' });
  await page.getByLabel('Tempo da prévia').fill('0');
  const initial = await canvas.evaluate(node => node.toDataURL());
  await page.getByLabel('Tempo da prévia').fill('0.5');
  await expect.poll(() => canvas.evaluate(node => node.toDataURL())).not.toBe(initial);
  await page.getByRole('button', { name: 'Reproduzir animação', exact: true }).click();
  await page.getByRole('button', { name: 'Pausar animação', exact: true }).click();
  await page.screenshot({ path: '.local/qa-motion.png', fullPage: true });
  await page.getByRole('button', { name: 'Salvar estrutura', exact: true }).click();
  await expect(page.getByText('Estrutura salva.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Voltar à ficha', exact: true }).click();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Exportar personagem salvo', exact: true }).click();
  const download = await downloadPromise;
  const pack = await readFile(await download.path());
  const portable = JSON.parse(pack.toString());
  expect(portable.images).toHaveLength(1);
  expect(portable.templates.filter(t => t.name.endsWith(String(stamp)))).toHaveLength(2);
  portable.name = name + ' importada';
  await page.getByRole('button', { name: 'Voltar ao catálogo', exact: true }).click();
  await page.getByLabel('Pacote do personagem').setInputFiles({ name: download.suggestedFilename(), mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(portable)) });
  await page.getByRole('button', { name: 'Importar personagem completo', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Abrir ' + portable.name, exact: true })).toBeVisible();
  const catalog = await (await page.request.get('/api/internal/library')).json();
  const original = catalog.find(item => item.name === name), imported = catalog.find(item => item.name === portable.name);
  expect(imported.id).not.toBe(original.id);
  await page.getByRole('button', { name: /Meus livros/ }).click();
  await page.getByRole('button', { name: /Novo livro/ }).click();
  await page.getByLabel('Título do livro').fill(title);
  await page.getByLabel('Identificador (slug)').fill('animado-' + stamp);
  await page.getByRole('button', { name: 'Criar livro', exact: true }).click();
  await page.getByRole('tab', { name: 'Páginas', exact: true }).click();
  await page.getByRole('button', { name: 'Adicionar página' }).click();
  await page.getByLabel('Texto da página').fill('Luna dança entre as árvores.');
  await page.getByLabel('Personagem da Biblioteca').selectOption(imported.id);
  await page.getByRole('button', { name: 'Inserir personagem', exact: true }).click();
  // Imported templates retain their names but receive independent identifiers.
  await expect(page.getByLabel('Pose na página').locator('option').filter({ hasText: 'Em pé ' + stamp })).toHaveCount(2);
  const poses = await page.getByLabel('Pose na página').locator('option').evaluateAll(options => options.map(o => ({ value: o.value, text: o.textContent })));
  await page.getByLabel('Pose na página').selectOption(poses.findLast(o => o.text === 'Em pé ' + stamp).value);
  const motions = await page.getByLabel('Animação na página').locator('option').evaluateAll(options => options.map(o => ({ value: o.value, text: o.textContent })));
  await page.getByLabel('Animação na página').selectOption(motions.findLast(o => o.text === 'Balanço ' + stamp).value);
  await page.getByLabel('X na página', { exact: true }).fill('120');
  await page.getByRole('button', { name: 'Atualizar prévia da página', exact: true }).click();
  await expect(page.getByText('Prévia pronta.', { exact: true })).toBeVisible();
  await page.getByLabel('Tempo da prévia').fill('0.5');
  await page.getByRole('button', { name: 'Salvar página', exact: true }).click();
  await expect(page.getByText('Prévia pronta.', { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: new RegExp(title) }).click();
  await page.getByRole('tab', { name: 'Páginas', exact: true }).click();
  await expect(page.getByLabel('X na página', { exact: true })).toHaveValue('120');
  await expect(page.getByText('Prévia pronta.', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Atualizar prévia da página', exact: true })).toBeEnabled();
  const bounds = await page.locator('.page-content').boundingBox();
  const stageBounds = await page.getByRole('img', { name: 'Prévia da cena animada' }).boundingBox();
  expect(stageBounds.x + stageBounds.width).toBeLessThanOrEqual(bounds.x + bounds.width);
  await page.screenshot({ path: '.local/qa-page-scene.png', fullPage: true });
  await page.getByLabel('Texto da página').fill('Texto revisado, com a mesma personagem.');
  await page.getByRole('button', { name: 'Salvar página', exact: true }).click();
  await expect(page.getByLabel('Instância na página').locator('option')).toHaveCount(1);
  await expect(page.getByLabel('Animação na página')).not.toHaveValue('');
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
