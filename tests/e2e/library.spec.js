import { test, expect } from '@playwright/test';
import sharp from 'sharp';
test('categorias separadas, consulta, edição persistida e descarte de alterações', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('Usuário', { exact: true }).fill(process.env.E2E_USERNAME);
  await page.getByLabel('Senha', { exact: true }).fill(process.env.E2E_PASSWORD);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await page.getByRole('button', { name: /Biblioteca/ }).click();
  const stamp = Date.now();
  const name = 'Luna ' + stamp;
  const description = 'Uma exploradora curiosa. <script>não executar</script>';
  await page.getByLabel('Nome do elemento').fill(name);
  await page.getByLabel('Descrição do elemento').fill(description);
  await page.getByRole('button', { name: 'Criar personagem e adicionar imagens' }).click();
  await page.getByRole('button', { name: 'Voltar à ficha' }).click();
  await page.getByRole('button', { name: 'Voltar ao catálogo' }).click();
  await expect(page.getByRole('button', { name: 'Abrir ' + name, exact: true })).toBeVisible();
  await page.getByRole('tab', { name: /Cenários/ }).click();
  await expect(page.getByRole('button', { name: 'Abrir ' + name, exact: true })).toHaveCount(0);
  await page.getByLabel('Nome do elemento').fill('Bosque ' + stamp);
  await page.getByRole('button', { name: 'Cadastrar elemento' }).click();
  await expect(page.getByRole('button', { name: 'Abrir Bosque ' + stamp })).toBeVisible();
  await page.getByRole('tab', { name: /Objetos/ }).click();
  await expect(page.getByRole('button', { name: 'Abrir Bosque ' + stamp })).toHaveCount(0);
  await page.getByRole('tab', { name: /Personagens/ }).click();
  const buffer = await sharp({ create: { width: 48, height: 64, channels: 4, background: '#7755cc80' } }).png().toBuffer();
  const imageName = 'Retrato ' + stamp;
  await page.getByRole('button', { name: 'Começar com um PNG' }).click();
  await page.getByLabel('Arquivo da ilustração').setInputFiles({ name: 'luna.png', mimeType: 'image/png', buffer });
  await page.getByLabel('Nome da ilustração').fill(imageName);
  await page.getByRole('button', { name: 'Importar imagem', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Abrir ' + imageName })).toBeVisible();
  await page.getByRole('button', { name: 'Abrir ' + name, exact: true }).click();
  await expect(page.getByLabel('Descrição do elemento')).toHaveValue(description);
  await page.getByLabel('Imagem do elemento').selectOption({ label: imageName });
  await expect(page.getByRole('img', { name: 'Imagem de ' + name })).toHaveJSProperty('naturalWidth', 48);
  await page.getByLabel('Nome do elemento').fill(name + ' editada');
  await page.getByLabel('Descrição do elemento').fill('Descrição revisada.');
  await page.getByRole('button', { name: 'Salvar cadastro', exact: true }).click();
  await expect(page.getByRole('heading', { name: name + ' editada', exact: true })).toBeVisible();
  await page.screenshot({ path: '.local/qa-library-detail.png', fullPage: true });
  await page.reload();
  await page.getByRole('button', { name: /Biblioteca/ }).click();
  await page.getByRole('button', { name: 'Abrir ' + name + ' editada', exact: true }).click();
  await expect(page.getByLabel('Descrição do elemento')).toHaveValue('Descrição revisada.');
  await expect(page.getByRole('img', { name: 'Imagem de ' + name + ' editada' })).toHaveJSProperty('naturalWidth', 48);
  await page.getByLabel('Nome do elemento').fill('Rascunho descartável');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Recarregar cadastro' }).click();
  await expect(page.getByLabel('Nome do elemento')).toHaveValue(name + ' editada');
  await page.getByLabel('Nome do elemento').fill('Alteração não salva');
  page.once('dialog', dialog => dialog.dismiss());
  await page.getByRole('tab', { name: /Cenários/ }).click();
  await expect(page.getByLabel('Nome do elemento')).toHaveValue('Alteração não salva');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('tab', { name: /Cenários/ }).click();
  await expect(page.getByRole('heading', { name: 'Cenários', exact: true })).toBeVisible();
});
